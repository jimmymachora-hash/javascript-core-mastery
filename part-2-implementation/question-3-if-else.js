// ==========================================
// 1. Basic if/else
// ==========================================

const age = 23;

if (age >= 18) {
    console.log("You are an adult.");
} else {
    console.log("You are a minor.");
}


// ==========================================
// 2. if / else if / else
// ==========================================

const score = 75;

if (score >= 80) {
    console.log("Grade A");
} else if (score >= 70) {
    console.log("Grade B");
} else if (score >= 60) {
    console.log("Grade C");
} else if (score >= 50) {
    console.log("Grade D");
} else {
    console.log("Grade F");
}


// ==========================================
// 3. Checking a condition
// ==========================================

const temperature = 30;

if (temperature > 25) {
    console.log("It is a hot day.");
} else {
    console.log("It is a cool day.");
}